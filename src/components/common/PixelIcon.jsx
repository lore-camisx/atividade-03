export default function PixelIcon({ name, size = 16, className = '', title }) {
  const grid = ICONS[name]
  if (!grid) return null

  const rects = []
  grid.forEach((row, y) => {
    ;[...row].forEach((cell, x) => {
      if (cell === '.') return
      rects.push(
        <rect
          key={`${x}-${y}`}
          x={x}
          y={y}
          width="1"
          height="1"
          fill={cell === 'w' ? 'var(--px-shine)' : 'currentColor'}
        />,
      )
    })
  })

  return (
    <svg
      className={`pixel-icon ${className}`}
      viewBox="0 0 8 8"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {rects}
    </svg>
  )
}
